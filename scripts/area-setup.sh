#!/usr/bin/env bash
# Set up an area worktree so it does not collide with the other seven (docs/parallel.md).
#
#   scripts/area-setup.sh <area> [--seed]
#
# Writes .env at the worktree root (only if absent), creates database toolbar_<area> on the
# shared compose Postgres, applies drizzle/ migrations, and with --seed loads the seed captures.
# Then: `set -a; . ./.env; set +a` in each shell before running dev servers or e2e.
set -euo pipefail

areas=(server-core auth capture ext-ui editor viewer dashboard agent)
area=${1:-}
i=-1
for n in "${!areas[@]}"; do [[ "${areas[$n]}" == "$area" ]] && i=$n; done
if (( i < 0 )); then
  echo "usage: $0 <$(IFS="|"; echo "${areas[*]}")> [--seed]" >&2
  exit 2
fi

root=$(git rev-parse --show-toplevel)
db="toolbar_${area//-/_}"
admin_url=${ADMIN_DATABASE_URL:-postgres://toolbar:toolbar@localhost:5432/toolbar}
db_url="${admin_url%/*}/$db"

if [[ ! -f "$root/.env" ]]; then
  cat > "$root/.env" <<ENV
# Area: $area (index $i). Generated by scripts/area-setup.sh; see docs/parallel.md.
DEV_PORT=$((3100 + i))
PUBLIC_URL=http://localhost:$((3100 + i))
DATABASE_URL=$db_url
S3_KEY_PREFIX=$area/
WXT_DEV_PORT=$((3200 + i))
WXT_SERVER_URL=http://localhost:$((3100 + i))
SERVER_URL=http://localhost:$((3100 + i))
E2E_DISPLAY=:$((110 + i))
DISPLAY=:$((110 + i))
ENV
  echo "[area] wrote $root/.env"
else
  echo "[area] $root/.env exists, left as is"
fi

if ! psql "$admin_url" -tAc "select 1 from pg_database where datname = '$db'" | grep -q 1; then
  psql "$admin_url" -qc "create database $db"
  echo "[area] created database $db"
fi

cd "$root/apps/server"
DATABASE_URL=$db_url node scripts/migrate.ts
if [[ "${2:-}" == "--seed" ]]; then
  set -a; . "$root/.env"; set +a
  node scripts/seed.ts
fi
