const cache = new Map<string, boolean[][]>();

/** Cells of a character (true = ink); unknown characters draw as a box. */
export function glyph(ch: string): boolean[][] {
  const k = /[a-z]/.test(ch) ? ch.toUpperCase() : ch;
  const hit = cache.get(k);
  if (hit) return hit;
  const src = G[k] ?? '#####|#   #|#   #|#   #|#   #|#   #|#####';
  const rows = src.split('|').map((r) => [...r.padEnd(5)].map((c) => c === '#'));
  cache.set(k, rows);
  return rows;
}

